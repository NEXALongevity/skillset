#!/usr/bin/env python3
"""Generate db/seed.sql from data/hospitals/*.yaml (and data/doctors/*.yaml when present).

The YAML files in this repo stay the open-source source of truth; the database is loaded from them.
Usage: python db/seed.py > db/seed.sql   (requires pyyaml)
"""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parent.parent


def q(v):
    if v is None:
        return "null"
    if isinstance(v, (list, tuple)):
        return "array[" + ",".join(q(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def source(title, url):
    return f"(select id from kb.sources where title = {q(title)} and url is not distinct from {q(url)})"


def main():
    out = ["-- GENERATED by db/seed.py from data/*.yaml. Do not edit.", "begin;"]
    sources = set()
    rows = []
    for f in sorted((ROOT / "data/hospitals").glob("*.yaml")):
        rows += yaml.safe_load(f.read_text(encoding="utf-8")) or []
    for r in rows:
        sources.add((r["source_list"], r.get("source_url")))
    for t, u in sorted(sources, key=lambda s: s[0]):
        out.append(f"insert into kb.sources (title, url) values ({q(t)}, {q(u)}) on conflict do nothing;")
    for r in rows:
        intl = r.get("international_dept") or {}
        out.append(
            "insert into kb.hospitals (id,name_zh,name_en,type,grade,city,province,website,intl_dept_name,intl_dept_phone,"
            "intl_dept_url,strengths,notes,verified_on) values ("
            + ",".join(q(x) for x in [r["id"], r["name_zh"], r["name_en"], r["type"], r.get("grade"), r["city"],
                                      r["province"], r.get("website"), intl.get("name"), intl.get("phone"),
                                      intl.get("url"), r.get("strengths") or [], r.get("notes"), str(r["verified_on"])])
            + ") on conflict (id) do update set name_zh=excluded.name_zh, name_en=excluded.name_en, type=excluded.type,"
            " grade=excluded.grade, city=excluded.city, province=excluded.province, website=excluded.website,"
            " intl_dept_name=excluded.intl_dept_name, intl_dept_phone=excluded.intl_dept_phone,"
            " intl_dept_url=excluded.intl_dept_url, strengths=array(select distinct unnest(kb.hospitals.strengths || excluded.strengths)), notes=excluded.notes,"
            " verified_on=excluded.verified_on;")
        for d in r["directions"]:
            out.append(f"insert into kb.hospital_directions values ({q(r['id'])}, {q(d)}) on conflict do nothing;")
        rk = r.get("ranking")
        if rk:
            out.append(
                "insert into kb.hospital_rankings (hospital_id,source_id,list_name,year,specialty,rank) values ("
                f"{q(r['id'])}, {source(r['source_list'], r.get('source_url'))}, {q(rk.get('list'))}, {q(rk.get('year'))},"
                f" {q(rk.get('specialty'))}, {q(rk.get('rank'))}) on conflict (hospital_id, source_id, specialty)"
                " do update set rank = excluded.rank, year = excluded.year;")
    out.append("commit;")
    print("\n".join(out))


if __name__ == "__main__":
    main()
