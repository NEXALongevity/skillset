#!/usr/bin/env python3
"""Bundle MCP data + knowledge base into a single Cloudflare Worker file: mcp/dist/worker.js

Usage: python mcp/build.py   (requires pyyaml)
"""
import json
from pathlib import Path
import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def main():
    hospitals, verified = [], set()
    for f in sorted((ROOT / "data/hospitals").glob("*.yaml")):
        for r in yaml.safe_load(f.read_text(encoding="utf-8")) or []:
            r["verified_on"] = str(r.get("verified_on"))
            verified.add(r["verified_on"])
            hospitals.append(r)
    data = {
        "visa": json.loads((HERE / "data/visa.json").read_text(encoding="utf-8")),
        "costs": json.loads((HERE / "data/cost_checklists.json").read_text(encoding="utf-8")),
        "channels": json.loads((HERE / "data/verification_channels.json").read_text(encoding="utf-8")),
        "hospitals": hospitals,
        "hospitals_as_of": max(verified) if verified else None,
    }
    src = (HERE / "src/worker.js").read_text(encoding="utf-8")
    out = HERE / "dist/worker.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text("// GENERATED by mcp/build.py — edit mcp/src and mcp/data instead.\n"
                   f"const DATA = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n" + src, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB, {len(hospitals)} hospitals)")


if __name__ == "__main__":
    main()
